/**
 * Named queries and statements executed via a {@link jakarta.persistence.TypedQueryReference}
 * or a {@link jakarta.persistence.StatementReference} with arguments, as generated by the
 * Hibernate Processor for Jakarta Data repositories.
 */
@Timeout(value = 10, timeUnit = MINUTES)
public class MutinyQueryReferenceTest extends BaseReactiveTest {

	private static final String FIND_BY_NAME = Queries.class.getCanonicalName() + "#findByName(java.lang.String)";
	private static final String DELETE_BY_NAME = Queries.class.getCanonicalName() + "#deleteByName(java.lang.String)";

	@Override
	protected Collection<Class<?>> annotatedEntities() {
		return List.of( Pig.class, Farm.class );
	}

	@Override
	protected void addEntities(Configuration configuration) {
		super.addEntities( configuration );
		// Not an entity, but declares the static queries
		configuration.addAnnotatedClass( Queries.class );
	}

	private static StaticTypedQueryReference<Pig> findByName(String name) {
		return findByName( name, null );
	}

	private static StaticTypedQueryReference<Pig> findByName(
			String name,
			String entityGraphName,
			TypedQuery.Option... options) {
		return new StaticTypedQueryReference<>(
				FIND_BY_NAME,
				Queries.class,
				"findByName",
				Pig.class,
				List.of( String.class ),
				List.of( "name" ),
				List.of( name ),
				entityGraphName,
				Map.of(),
				options
		);
	}

	private static StaticStatementReference deleteByName(String name, Statement.Option... options) {
		return new StaticStatementReference(
				DELETE_BY_NAME,
				Queries.class,
				"deleteByName",
				List.of( String.class ),
				List.of( "name" ),
				List.of( name ),
				Map.of(),
				options
		);
	}

	@Test
	public void testSessionCreateQueryFromReferenceWithEntityGraph(VertxTestContext context) {
		test( context, getMutinySessionFactory()
				.withTransaction( session -> {
					final Farm farm = new Farm( 1, "Sunny Farm" );
					return session.persist( farm )
							.chain( () -> session.persist( new Pig( 2, "Xavier", farm ) ) );
				} )
				.chain( () -> getMutinySessionFactory().withSession( session -> session
						.createQuery( findByName( "Xavier", "Pig.farm" ) )
						.getSingleResult()
						.invoke( pig -> assertThat( Hibernate.isInitialized( pig.farm ) ).isTrue() ) ) )
				.chain( () -> getMutinySessionFactory().withSession( session -> session
						.createQuery( findByName( "Xavier", null ) )
						.getSingleResult()
						.invoke( pig -> assertThat( Hibernate.isInitialized( pig.farm ) ).isFalse() ) ) )
		);
	}

	@Test
	public void testStatelessSessionCreateQueryFromReferenceWithEntityGraph(VertxTestContext context) {
		test( context, getMutinySessionFactory()
				.withTransaction( session -> {
					final Farm farm = new Farm( 1, "Sunny Farm" );
					return session.persist( farm )
							.chain( () -> session.persist( new Pig( 2, "Xavier", farm ) ) );
				} )
				.chain( () -> getMutinySessionFactory().withStatelessSession( session -> session
						.createQuery( findByName( "Xavier", "Pig.farm" ) )
						.getSingleResult()
						.invoke( pig -> assertThat( Hibernate.isInitialized( pig.farm ) ).isTrue() ) ) )
		);
	}

	@Test
	public void testSessionCreateQueryFromReferenceWithOptions(VertxTestContext context) {
		test( context, getMutinySessionFactory().withTransaction( session -> session
				.persist( new Pig( 1, "Aloi", null ) )
				// without the option, the pending insert is flushed before the query
				.chain( () -> session.createQuery( findByName( "Aloi", null ) ).getResultList() )
				.invoke( pigs -> assertThat( pigs ).hasSize( 1 ) )
				.chain( () -> session.persist( new Pig( 2, "Xavier", null ) ) )
				.chain( () -> session.createQuery( findByName( "Xavier", null, QueryFlushMode.NO_FLUSH ) )
						.getResultList() )
				.invoke( pigs -> assertThat( pigs ).isEmpty() ) )
		);
	}

	@Test
	public void testSessionCreateStatementFromReferenceWithOptions(VertxTestContext context) {
		test( context, getMutinySessionFactory().withTransaction( session -> session
				.persist( new Pig( 1, "Aloi", null ) )
				// the pending insert is not flushed, so there is nothing to delete
				.chain( () -> session.createStatement( deleteByName( "Aloi", QueryFlushMode.NO_FLUSH ) ).executeUpdate() )
				.invoke( rows -> assertThat( rows ).isEqualTo( 0 ) )
				// the flush mode only applies to the statement
				.chain( () -> session.createStatement( deleteByName( "Aloi" ) ).executeUpdate() )
				.invoke( rows -> assertThat( rows ).isEqualTo( 1 ) ) )
		);
	}

	@Test
	public void testSessionCreateQueryFromReferenceWithArguments(VertxTestContext context) {
		test( context, getMutinySessionFactory().withTransaction( session -> session
				.persistAll( new Pig( 1, "Aloi", null ), new Pig( 2, "Xavier", null ) )
				.chain( session::flush )
				.chain( () -> session.createQuery( findByName( "Xavier" ) ).getSingleResult() )
				.invoke( pig -> assertThat( pig.id ).isEqualTo( 2 ) ) )
		);
	}

	@Test
	public void testStatelessSessionCreateQueryFromReferenceWithArguments(VertxTestContext context) {
		test( context, getMutinySessionFactory().withStatelessTransaction( session -> session
				.insertMultiple( List.of( new Pig( 1, "Aloi", null ), new Pig( 2, "Xavier", null ) ) )
				.chain( () -> session.createQuery( findByName( "Xavier" ) ).getSingleResult() )
				.invoke( pig -> assertThat( pig.id ).isEqualTo( 2 ) ) )
		);
	}

	@Test
	public void testSessionCreateStatementFromReferenceWithArguments(VertxTestContext context) {
		test( context, getMutinySessionFactory().withTransaction( session -> session
				.persistAll( new Pig( 1, "Aloi", null ), new Pig( 2, "Xavier", null ) )
				.chain( session::flush )
				.chain( () -> session.createStatement( deleteByName( "Aloi" ) ).executeUpdate() )
				.invoke( rows -> assertThat( rows ).isEqualTo( 1 ) ) )
		);
	}

	@Test
	public void testStatelessSessionCreateStatementFromReferenceWithArguments(VertxTestContext context) {
		test( context, getMutinySessionFactory().withStatelessTransaction( session -> session
				.insertMultiple( List.of( new Pig( 1, "Aloi", null ), new Pig( 2, "Xavier", null ) ) )
				.chain( () -> session.createStatement( deleteByName( "Aloi" ) ).executeUpdate() )
				.invoke( rows -> assertThat( rows ).isEqualTo( 1 ) ) )
		);
	}

	@Test
	public void testSessionCreateStatementFromReferenceKeepsNamedQueryOptions(VertxTestContext context) {
		test( context, getMutinySessionFactory().withTransaction( session -> session
				.persist( new Pig( 1, "Aloi", null ) )
				// the named statement is declared with flush mode MANUAL, so the pending insert is not flushed
				.chain( () -> session.createStatement( deleteByNameNoFlush( "Aloi" ) ).executeUpdate() )
				.invoke( rows -> assertThat( rows ).isEqualTo( 0 ) ) )
		);
	}

	@Test
	public void testStatelessSessionCreateStatementFromReferenceKeepsNamedQueryOptions(VertxTestContext context) {
		test( context, getMutinySessionFactory().withStatelessTransaction( session -> {
			final MutationQuery query = session.createStatement( deleteByNameNoFlush( "Aloi" ) );
			assertThat( query.getComment() ).isEqualTo( "Pig.deleteByNameNoFlush" );
			return query.executeUpdate();
		} ) );
	}

	@Test
	public void testSessionCreateQueryFromReferenceToStatement(VertxTestContext context) {
		test( context, assertThrown(
				IllegalSelectQueryException.class,
				getMutinySessionFactory().withSession( session -> session
						.createQuery( new StaticTypedQueryReference<>(
								DELETE_BY_NAME,
								Queries.class,
								"deleteByName",
								Pig.class,
								List.of( String.class ),
								List.of( "name" ),
								List.of( "Aloi" )
						) )
						.getResultList() )
		) );
	}

	@Test
	public void testSessionCreateStatementFromReferenceToQuery(VertxTestContext context) {
		test( context, assertThrown(
				IllegalMutationQueryException.class,
				getMutinySessionFactory().withTransaction( session -> session
						.createStatement( new StaticStatementReference(
								FIND_BY_NAME,
								Queries.class,
								"findByName",
								List.of( String.class ),
								List.of( "name" ),
								List.of( "Aloi" ),
								Map.of()
						) )
						.executeUpdate() )
		) );
	}

	private static StaticStatementReference deleteByNameNoFlush(String name) {
		return new StaticStatementReference(
				"Pig.deleteByNameNoFlush",
				Pig.class,
				"deleteByNameNoFlush",
				List.of( String.class ),
				List.of( "name" ),
				List.of( name ),
				Map.of()
		);
	}

	@Entity(name = "Pig")
	@Table(name = "QueryReferencePig")
	@NamedStatement(
			name = "Pig.deleteByNameNoFlush",
			statement = "delete from Pig where name = :name",
			hints = {
					@QueryHint(name = HINT_FLUSH_MODE, value = "MANUAL"),
					@QueryHint(name = HINT_COMMENT, value = "Pig.deleteByNameNoFlush")
			}
	)
	@NamedEntityGraph(name = "Pig.farm", attributeNodes = @NamedAttributeNode("farm"))
	public static class Pig {
		@Id
		Integer id;
		String name;
		@ManyToOne(fetch = FetchType.LAZY)
		Farm farm;

		public Pig() {
		}

		public Pig(Integer id, String name, Farm farm) {
			this.id = id;
			this.name = name;
			this.farm = farm;
		}
	}

	@Entity(name = "Farm")
	@Table(name = "QueryReferenceFarm")
	public static class Farm {
		@Id
		Integer id;
		String name;

		public Farm() {
		}

		public Farm(Integer id, String name) {
			this.id = id;
			this.name = name;
		}
	}

	/**
	 * Static queries, registered when the persistence unit is bootstrapped.
	 */
	abstract static class Queries {
		@JakartaQuery("from Pig where name = :name")
		abstract List<Pig> findByName(String name);

		@JakartaQuery("delete from Pig where name = :name")
		abstract int deleteByName(String name);
	}
}
